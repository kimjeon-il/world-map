import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const requiredLayeredFiles = Object.freeze([
  'assets/css/tokens/ui-v2.css',
  'assets/css/primitives/controls.css',
  'assets/css/components/surface.css',
  'assets/css/components/content.css',
  'assets/css/components/command-row.css',
  'assets/css/components/workflows.css',
  'assets/css/layout/surfaces.css',
  'assets/css/features/layer-panel.css',
  'assets/css/components/editor-shell.css',
  'assets/css/components/panels.css',
  'assets/css/components/mobile-sheets.css',
  'assets/css/components/feedback.css',
  'assets/css/utilities/accessibility.css',
]);
const bootstrapPath = path.join(root, 'assets/js/bootstrap.js');
const appStylesheetPath = path.join(root, 'assets/css/app.css');
const bundlePath = path.join(root, 'assets/css/ui-v2.bundle.css');
const modalBundlePath = path.join(root, 'assets/css/ui-modal.bundle.css');
const modalSourceFiles = Object.freeze(['assets/css/components/modals.css']);
const indexPath = path.join(root, 'index.html');
const uiRuntimePath = path.join(root, 'assets/js/modules/ui-runtime.js');
const componentDocPath = path.join(root, 'docs/architecture/ui-components-v2.md');
const retiredArtifacts = Object.freeze([
  'assets/css/phase1-ui-cleanup.css',
  'assets/js/modules/phase1-ui-cleanup.js',
  'assets/js/modules/mobile-sheet-v2.js',
  'assets/js/modules/state-feedback-v2.js',
  'assets/js/modules/accessibility-qa-v2.js',
]);
const failures = [];

function collectModalDeclarationKeys(source) {
  const keys = new Set();
  const withoutComments = source.replace(/\/\*[\s\S]*?\*\//g, '');
  const rulePattern = /([^{}]+)\{([^{}]*)\}/g;
  let match;
  while ((match = rulePattern.exec(withoutComments))) {
    const selectors = match[1].split(',').map(value => value.trim()).filter(Boolean);
    const properties = match[2]
      .split(';')
      .map(value => value.trim())
      .filter(Boolean)
      .map(declaration => {
        const separator = declaration.indexOf(':');
        return separator > 0 ? declaration.slice(0, separator).trim() : '';
      })
      .filter(Boolean);
    for (const selector of selectors) {
      if (!/(?:modal|gis|historical|coast-reconciliation)/i.test(selector)) continue;
      for (const property of properties) keys.add(`${selector}\u0000${property}`);
    }
  }
  return keys;
}

for (const relativePath of requiredLayeredFiles) {
  if (!fs.existsSync(path.join(root, relativePath))) {
    failures.push(`missing canonical layered stylesheet: ${relativePath}`);
  }
}
for (const relativePath of modalSourceFiles) {
  if (!fs.existsSync(path.join(root, relativePath))) failures.push(`missing modal stylesheet source: ${relativePath}`);
}

if (!fs.existsSync(componentDocPath)) {
  failures.push('missing UI v2 component documentation: docs/architecture/ui-components-v2.md');
}

if (!fs.existsSync(bundlePath)) {
  failures.push('missing canonical UI bundle: assets/css/ui-v2.bundle.css');
} else {
  const bundle = fs.readFileSync(bundlePath, 'utf8');
  const sourceContents = requiredLayeredFiles.map(relativePath => ({
    relativePath,
    content: fs.readFileSync(path.join(root, relativePath), 'utf8').trim(),
  }));
  const expectedBundle = [
    '/* Generated by scripts/build-ui-bundle.mjs. Do not edit manually. */',
    `/* source-count: ${requiredLayeredFiles.length} */`,
    ...sourceContents.flatMap(({ relativePath, content }) => [
      `/* source: ${relativePath} */`,
      content,
    ]),
    '',
  ].join('\n\n');
  if (bundle !== expectedBundle) failures.push('UI bundle is stale; run pnpm build:ui-bundle');
  let previousIndex = -1;
  for (const relativePath of requiredLayeredFiles) {
    const marker = `/* source: ${relativePath} */`;
    const index = bundle.indexOf(marker);
    if (index < 0) failures.push(`UI bundle is missing source: ${relativePath}`);
    else if (index <= previousIndex) failures.push(`UI bundle source order is invalid: ${relativePath}`);
    previousIndex = index;
  }

  const expectedModalBundle = [
    '/* Generated by scripts/build-ui-bundle.mjs. Do not edit manually. */',
    `/* modal-source-count: ${modalSourceFiles.length} */`,
    ...modalSourceFiles.flatMap(relativePath => [
      `/* modal-source: ${relativePath} */`,
      fs.readFileSync(path.join(root, relativePath), 'utf8').trim(),
    ]),
    '',
  ].join('\n\n');
  if (!fs.existsSync(modalBundlePath)) failures.push('missing lazy modal UI bundle: assets/css/ui-modal.bundle.css');
  else if (fs.readFileSync(modalBundlePath, 'utf8') !== expectedModalBundle) failures.push('modal UI bundle is stale; run pnpm build:ui-bundle');

  if (fs.existsSync(appStylesheetPath)) {
    const appModalDeclarations = collectModalDeclarationKeys(fs.readFileSync(appStylesheetPath, 'utf8'));
    const modalDeclarations = collectModalDeclarationKeys(expectedModalBundle);
    const duplicateOwnership = [...appModalDeclarations].filter(key => modalDeclarations.has(key));
    if (duplicateOwnership.length) {
      failures.push(`app.css and modal bundle duplicate selector/property ownership: ${duplicateOwnership.slice(0, 5).map(key => key.replace('\u0000', ' / ')).join(', ')}`);
    }
  }
}

for (const relativePath of retiredArtifacts) {
  if (fs.existsSync(path.join(root, relativePath))) {
    failures.push(`retired UI compatibility artifact returned: ${relativePath}`);
  }
}

if (!fs.existsSync(bootstrapPath)) {
  failures.push('missing canonical bootstrap: assets/js/bootstrap.js');
} else {
  const bootstrap = fs.readFileSync(bootstrapPath, 'utf8');
  if (bootstrap.includes("const UI_BUNDLE = '../css/ui-v2.bundle.css'")) failures.push('bootstrap still installs ui-v2.bundle.css dynamically');
  if (!bootstrap.includes('../css/ui-modal.bundle.css')) failures.push('bootstrap does not expose lazy ui-modal.bundle.css loading');
  const individualLinks = requiredLayeredFiles
    .map(relativePath => relativePath.replace('assets/css/', '../css/'))
    .filter(runtimeRelative => bootstrap.includes(runtimeRelative));
  if (individualLinks.length) failures.push(`bootstrap still installs individual UI stylesheets: ${individualLinks.join(', ')}`);
  if (!bootstrap.includes("./modules/ui-runtime.js")) {
    failures.push('bootstrap does not initialize canonical ui-runtime.js');
  }
  if (/phase1-ui-cleanup|installPhaseOneUiCleanup|PL-UI-CLEANUP/.test(bootstrap)) {
    failures.push('bootstrap still contains retired phase cleanup wiring');
  }
}

if (!fs.existsSync(indexPath) || !fs.readFileSync(indexPath, 'utf8').includes('data-pandolab-ui-v2="ui-v2-bundle"')) {
  failures.push('index.html does not statically own ui-v2.bundle.css');
}

if (!fs.existsSync(uiRuntimePath)) {
  failures.push('missing canonical UI runtime: assets/js/modules/ui-runtime.js');
}

if (failures.length) {
  console.error(`UI layering audit failed with ${failures.length} issue(s):`);
  for (const failure of failures) console.error(`- ${failure}`);
  process.exitCode = 1;
} else {
  console.log(`UI layering audit passed: ${requiredLayeredFiles.length} canonical layered stylesheets, no phase cleanup runtime.`);
}
