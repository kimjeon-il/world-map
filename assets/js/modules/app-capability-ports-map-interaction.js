export function createMapInteractionPorts(providers) {
  return Object.freeze({
    ...createReadPorts(providers, PORT_SPECS),
    interactionStateCommands: Object.freeze({
      replaceGpuEditPreviewPackets: value => { providers.interactionPackets.currentGpuEditPreviewPackets = value; },
      replaceGpuInteractionFillItems: value => { providers.interactionPackets.currentGpuInteractionFillItems = value; },
      setHoverHit: value => { providers.pointerTargets.lastHoverHit = value; },
      setSelectionPacket: value => { providers.gpuScene.currentSelectionPacket = value; },
    }),
    mapHostCommands: Object.freeze({
      advanceVisualProjection: kind => { providers.mapHost.lastVisualProjectionKind = kind; providers.mapHost.visualProjectionRevision += 1; },
      installBaseSvg: value => { providers.objectCommands.baseSvg = value; },
      installFlatOceanLayer: value => { providers.objectCommands.flatOceanLayer = value; },
      installMapInputController: value => { providers.lifecycleAssembly.mapInputController = value; },
      installSelectionPass: value => { providers.gpuScene.selectionPass = value; },
      setReadyPromise: value => { providers.mapHost.mapHostReadyPromise = value; },
    }),
    surfaceCommands: Object.freeze({
      installEditorSurfaceTabs: value => { providers.workspaceSurfaces.editorSurfaceTabs = value; },
      replaceObjectChooserCandidates: value => { providers.projectSession.objectChooserCandidates = value; },
      setFileMenuTrigger: value => { providers.workspaceSurfaces.fileMenuTrigger = value; },
      setIgnoreNextMobileSheetPopstate: value => { providers.workspaceSurfaces.ignoreNextMobileSheetPopstate = value; },
      setMapModeContextActive: value => { providers.workspaceSurfaces.mapModeContextWasActive = value; },
    })
  });
}
